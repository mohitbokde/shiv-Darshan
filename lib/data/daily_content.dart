int _dayNumber(DateTime d) {
  return DateTime.utc(d.year, d.month, d.day)
      .difference(DateTime.utc(2024, 1, 1))
      .inDays;
}

Mantra mantraFor(DateTime d) => mantras[_dayNumber(d) % mantras.length];

Katha kathaFor(DateTime d) => kathas[(_dayNumber(d) + 3) % kathas.length];
